"""imitator_cb_final.py -- P2 Viec 1 (item 4): last IMITATOR attempt for the circuit-breaker
(CB) compositions, with a purely DISCRETE encoding (no stopwatch, no clock other than the
frame tick xf), as decided at CP1 (#5).

Box: T <= 6, W <= 4, d <= 2 (block mode: busy iff fewer than d frames since the last
dispatch), b = 0, kappa = 1, R <= 12. One transition = one frame (xf = 1, reset).
Discrete state:
  a   frames since the last dispatch at the decision of the current frame (a >= 1)
  f   G1's counter fsl (saturated at WMAX + 2; the cap stays due once it is due)
  r   refresh counter, refresh frame iff r = T - 1 (adversarial phase chosen in loc ini)
  g, pl  (exact CB only) bypass age mod K and probe frames left, constants K, P
bad  <=> a >= R - d + 1 at a frame boundary (a run of R - d non-dispatch frames).
Three models, each for '>=' (CAPOFF 0) and '>' (CAPOFF 1):
  cbabs   abstract CB, free switching ACTIVE <-> BYPASS (Prop. 2.6; P1 model CB_d_block)
  cbK4P2  exact probe schedule K = 4, P = 2 (gcd 2: Prop. 2.7 predicts no hole for d = 2)
  cbK6P3  exact probe schedule K = 6, P = 3 (gcd 3: Prop. 2.7 predicts a hole for d = 2)
Each run: `#synth EF(loc[ctrl] = bad)`, timeout 3,600 s; then the synthesised constraint is
evaluated on every integer point of the box and compared with the explicit-state engines
(region_bruteforce.rstar with cb = 1 for cbabs; cb_rule_ext.lmax_cb with adversarial refresh
phase for the exact schedules -- lmax_cb_exact pins the phase to pos % T == 0).
Outputs: results/region_ext/imi_cb_final/*.imi|.res, results/region_ext/imitator_cb_final.log,
         results/region_ext/imitator_cb_final.json
Usage: python code/imitator_cb_final.py --seed 42 [--timeout 3600] [--only cbabs_ge]
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from fractions import Fraction
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cb_rule_ext import gamma  # noqa: E402
from region_bruteforce import rstar  # noqa: E402
from region_imitator import compile_constraint, eval_constraint, wsl_path  # noqa: E402

TOPIC_DIR = Path(__file__).resolve().parent.parent
OUT = TOPIC_DIR / "results" / "region_ext"
IMI = OUT / "imi_cb_final"
LOG = OUT / "imitator_cb_final.log"
BOX = {"TMAX": 6, "WMAX": 4, "DMAX": 2, "RMAX": 12}
MODELS = {"cbabs": None, "cbK4P2": (4, 2), "cbK6P3": (6, 3)}


def g1_frame(c: int, rf: bool):
    """G1 decides one frame. Returns list of (guards, updates). rf: this is a refresh frame."""
    W2 = BOX["WMAX"] + 2
    out = [(["a >= d"], ["a := 1", "f := 0"])]                          # dispatch
    if not rf:                                                          # closed, free
        out.append((["a >= d", f"f <= W + {c} - 1", f"a <= {BOX['RMAX']}"],
                    ["a := a + 1", "f := f + 1"]))
    out.append((["a <= d - 1", f"f <= {W2 - 1}", f"a <= {BOX['RMAX']}"],  # busy
                ["a := a + 1", "f := f + 1"]))
    out.append((["a <= d - 1", f"f >= {W2}", f"a <= {BOX['RMAX']}"], ["a := a + 1"]))
    return out


def byp_frame():
    """Pure bypass frame: detector dispatched whenever free, G1 frozen."""
    return [(["a >= d"], ["a := 1"]),
            (["a <= d - 1", f"a <= {BOX['RMAX']}"], ["a := a + 1"])]


def refresh_variants():
    return [(True, ["r = T - 1"], ["r := 0"]), (False, ["r <= T - 2"], ["r := r + 1"])]


def tr(src, guards, upds, dst):
    g = " & ".join(["xf = 1"] + guards)
    u = ", ".join(["xf := 0"] + upds)
    return f"  when {g} do {{{u}}} goto {dst};"


def model(name: str, c: int) -> str:
    KP = MODELS[name]
    L = ["(* generated by code/imitator_cb_final.py; discrete encoding, one frame per edge *)",
         "var", "  xf : clock;", "  a, f, r, g, pl : rational;", "  T, W, R, d : parameter;",
         "", "automaton ctrl", "  actions: ;", "",
         "  loc ini: invariant xf <= 0",
         "    when r <= T - 2 do {r := r + 1} goto ini;",
         "    when True goto act;", ""]
    bad = "  when xf = 1 & a + d >= R + 1 goto bad;"
    # ACTIVE
    L += ["  loc act: invariant xf <= 1", bad]
    for rf, rg, ru in refresh_variants():
        for gg, uu in g1_frame(c, rf):
            L.append(tr("act", gg + rg, uu + ru, "act"))
    if KP is None:
        L += ["  when xf = 0 goto byp;", "", "  loc byp: invariant xf <= 1", bad]
        for rf, rg, ru in refresh_variants():
            for gg, uu in byp_frame():
                L.append(tr("byp", gg + rg, uu + ru, "byp"))
        L += ["  when xf = 0 goto act;", ""]
    else:
        K, P = KP
        # enter BYPASS: this frame is a bypass frame with age 0
        for rf, rg, ru in refresh_variants():
            for gg, uu in byp_frame():
                L.append(tr("act", gg + rg, uu + ru + ["g := 0", "pl := 0"], "byp"))
        L += ["", "  loc byp: invariant xf <= 1", bad]
        for rf, rg, ru in refresh_variants():
            for gg, uu in byp_frame():                       # next age < K: pure bypass
                L.append(tr("byp", gg + rg + [f"g <= {K - 2}"], uu + ru + ["g := g + 1"], "byp"))
            for gg, uu in g1_frame(c, rf):                   # age wraps: probe starts
                base = gg + rg + [f"g = {K - 1}"]
                if P == 1:
                    L.append(tr("byp", base, uu + ru + ["g := 0"], "byp"))
                    L.append(tr("byp", base, uu + ru + ["g := 0"], "act"))
                else:
                    L.append(tr("byp", base, uu + ru + ["g := 0", f"pl := {P - 1}"], "prb"))
        L += ["", "  loc prb: invariant xf <= 1", bad]
        for rf, rg, ru in refresh_variants():
            for gg, uu in g1_frame(c, rf):
                L.append(tr("prb", gg + rg + ["pl >= 2"], uu + ru + ["g := g + 1", "pl := pl - 1"],
                            "prb"))
                # last probe frame: stay in BYPASS or exit to ACTIVE
                L.append(tr("prb", gg + rg + ["pl = 1"], uu + ru + ["g := g + 1", "pl := 0"], "byp"))
                L.append(tr("prb", gg + rg + ["pl = 1"], uu + ru + ["pl := 0"], "act"))
        L.append("")
    L += ["  loc bad: invariant True", "end", "", "init := {", "  discrete =",
          "    loc[ctrl] := ini, a := 1, f := 0, r := 0, g := 0, pl := 0", "  ;",
          "  continuous =",
          "    xf = 0",
          f"    & T >= 1 & T <= {BOX['TMAX']}",
          f"    & W >= 0 & W <= {BOX['WMAX']}",
          f"    & R >= 1 & R <= {BOX['RMAX']}",
          f"    & d >= 0 & d <= {BOX['DMAX']}", "  ;", "}", ""]
    return "\n".join(L)


def log(msg: str) -> None:
    line = f"[{time.strftime('%Y-%m-%d %H:%M:%S')}] {msg}"
    print(line, flush=True)
    with LOG.open("a", encoding="utf-8") as fh:
        fh.write(line + "\n")


def run(stem: str, txt: str, timeout: int) -> dict:
    IMI.mkdir(parents=True, exist_ok=True)
    (IMI / f"{stem}.imi").write_text(txt, encoding="utf-8", newline="\n")
    (IMI / "bad.imiprop").write_text("property := #synth EF(loc[ctrl] = bad);\n",
                                     encoding="utf-8", newline="\n")
    for old in IMI.glob(f"{stem}*.res"):
        old.unlink()
    cmd = ["wsl.exe", "-d", "Ubuntu-24.04", "-u", "root", "--", "bash", "-lc",
           f"cd '{wsl_path(IMI)}' && timeout {timeout} /usr/local/bin/imitator '{stem}.imi' "
           f"bad.imiprop -output-prefix {stem} -merge yes"]
    t0 = time.time()
    r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    wall = time.time() - t0
    (IMI / f"{stem}.stdout.txt").write_text(r.stdout[-20000:] + "\n--- stderr ---\n" +
                                            r.stderr[-5000:], encoding="utf-8")
    res_p = IMI / f"{stem}.res"
    res = res_p.read_text(encoding="utf-8", errors="replace") if res_p.exists() else ""
    import re
    info = {"stem": stem, "returncode": r.returncode, "wall_s": round(wall, 1),
            "status": "finished" if res else ("timeout" if r.returncode == 124 else "error")}
    for key, pat in [("soundness", r"Constraint soundness\s*:\s*(.+)"),
                     ("termination", r"Termination\s*:\s*(.+)"),
                     ("n_states", r"Number of states\s*:\s*(\d+)"),
                     ("time_s", r"Total computation time\s*:\s*([\d.]+)")]:
        m = re.search(pat, res)
        info[key] = m.group(1).strip() if m else None
    m = re.search(r"BEGIN CONSTRAINT(.*?)END CONSTRAINT", res, re.S)
    info["constraint"] = m.group(1).strip() if m else None
    return info


def truth(name: str, T: int, W: int, ge: int, d: int) -> int:
    KP = MODELS[name]
    if KP is None:
        return rstar(T, W, ge, d, 1, 0, Fraction(1), 1)[1]
    return gamma(T, W, ge, d, KP[0], KP[1], 1, 1) + d   # adversarial refresh phase


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=42, help="unused (exhaustive); recorded")
    ap.add_argument("--timeout", type=int, default=3600)
    ap.add_argument("--only", default="")
    a = ap.parse_args()
    jp = OUT / "imitator_cb_final.json"
    summary = json.loads(jp.read_text(encoding="utf-8")) if jp.exists() else {}
    summary.update({"seed": a.seed, "box": BOX, "timeout_s": a.timeout,
                    "encoding": "discrete counters a, f, r (+ g, pl), one clock xf (frame tick)",
                    "options": "-merge yes", "imitator": "3.4 (WSL Ubuntu-24.04)"})
    summary.setdefault("runs", {})
    log(f"start; box {BOX}; timeout {a.timeout} s")
    for name in MODELS:
        for ge in (1, 0):
            stem = f"{name}_{'ge' if ge else 'gt'}"
            if a.only and stem not in a.only.split(","):
                continue
            log(f"run {stem}")
            info = run(stem, model(name, 0 if ge else 1), a.timeout)
            chk = {"n_points": 0, "n_mismatch": 0, "mismatch_head": []}
            disj = compile_constraint(info["constraint"])
            if disj is not None:
                for T in range(1, BOX["TMAX"] + 1):
                    for W in range(0, BOX["WMAX"] + 1):
                        for d in range(0, BOX["DMAX"] + 1):
                            Rs = truth(name, T, W, ge, d)
                            for R in range(1, BOX["RMAX"] + 1):
                                bad_imi = eval_constraint(disj, {"T": T, "W": W, "R": R, "d": d})
                                chk["n_points"] += 1
                                if bad_imi != (R < Rs):
                                    chk["n_mismatch"] += 1
                                    if len(chk["mismatch_head"]) < 10:
                                        chk["mismatch_head"].append(
                                            {"T": T, "W": W, "d": d, "R": R,
                                             "imi_bad": bad_imi, "R_star": Rs})
            info["integer_check"] = chk
            info["constraint_n_disjuncts"] = len(disj) if disj is not None else None
            summary["runs"][stem] = {k: v for k, v in info.items() if k != "constraint"}
            log(f"{stem}: {info['status']} soundness={info['soundness']} "
                f"termination={info['termination']} time={info['time_s']} wall={info['wall_s']} "
                f"states={info['n_states']} check {chk['n_points']} pts {chk['n_mismatch']} mismatch")
            jp.write_text(json.dumps(summary, indent=1, default=str), encoding="utf-8")
    log("done")


if __name__ == "__main__":
    main()
